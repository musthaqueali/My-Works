def get_full_conversion_matrix() -> list[dict]:
    """Computes all supported (source -> target) conversion routes across the catalog."""
    routes = []
    for src_ext, src_data in FORMAT_CATALOG.items():
        targets = src_data.get("targets", [])
        for tgt in targets:
            uc = src_data.get("use_cases", {}).get(tgt, f"Convert {src_ext.upper()} into {tgt.upper()} standard.")
            routes.append({
                "from": src_ext,
                "from_name": src_data["name"],
                "category": src_data["category"],
                "to": tgt,
                "to_name": FORMAT_CATALOG.get(tgt, {}).get("name", tgt.upper()),
                "use_case": uc
            })
    return routes

def get_targets(input_ext: str) -> list[str]:
    ext = input_ext.lower().lstrip(".")
    if ext in FORMAT_CATALOG:
        return FORMAT_CATALOG[ext].get("targets", [])
    for key, val in FORMAT_CATALOG.items():
        if ext in val.get("extensions", []):
            return val.get("targets", [])
    return []

def get_use_case(input_ext: str, target_ext: str) -> str:
    ext = input_ext.lower().lstrip(".")
    tgt = target_ext.lower().lstrip(".")
    if ext in FORMAT_CATALOG:
        return FORMAT_CATALOG[ext].get("use_cases", {}).get(tgt, "")
    for key, val in FORMAT_CATALOG.items():
        if ext in val.get("extensions", []):
            return val.get("use_cases", {}).get(tgt, "")
    return ""

def is_supported(input_ext: str, target_ext: str) -> bool:
    targets = get_targets(input_ext)
    return target_ext.lower().lstrip(".") in [t.lower() for t in targets]

def get_format_info(input_ext: str):
    ext = input_ext.lower().lstrip(".")
    if ext in FORMAT_CATALOG:
        return ext, FORMAT_CATALOG[ext]
    for key, val in FORMAT_CATALOG.items():
        if ext in val.get("extensions", []):
            return key, val
    return None, None

